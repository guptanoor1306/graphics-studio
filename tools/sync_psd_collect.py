#!/usr/bin/env python3
"""Copy LA Studio's layer collector (source2psd.py COLLECT) into static/psd_collect.js.

Edit layers lists the same layers Make Layers puts in the PSD because both run this one script. Run this after
changing COLLECT in zo-studio:  python3 tools/sync_psd_collect.py /path/to/zo-studio/source2psd.py"""
import pathlib, re, sys

src = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "../zo-studio/source2psd.py").read_text()
m = re.search(r'^COLLECT = r"""\n(.*?)\n"""', src, re.S | re.M)
if not m:
    sys.exit("COLLECT not found in source2psd.py")
out = pathlib.Path(__file__).resolve().parents[1] / "static" / "psd_collect.js"
out.write_text("/* GENERATED by tools/sync_psd_collect.py from LA Studio's source2psd.py (COLLECT): the exact rule Make Layers uses\n"
               "   to decide what is a PSD layer. Do not edit here; edit source2psd.py and run the sync. */\n"
               "window.PSD_COLLECT = " + m.group(1).strip() + ";\n")
print("wrote", out, len(m.group(1)), "chars")
